package com.tracenixa.platform.evaluation.service;

import lombok.extern.slf4j.Slf4j;
import org.springframework.stereotype.Component;

import java.util.List;

@Slf4j
@Component
public class LlmJudgeEvaluator {

    public record Judgment(double faithfulnessScore, double relevanceScore, String reasoning) {}

    public Judgment evaluateResponse(
            String userInput,
            String agentOutput,
            List<String> toolsInvoked,
            List<String> requiredKeywords
    ) {
        if (agentOutput == null || agentOutput.isBlank()) {
            return new Judgment(0.0, 0.0, "Empty output generated by agent.");
        }

        double relevance = 100.0;
        double faithfulness = 100.0;
        StringBuilder reasoning = new StringBuilder();

        // 1. Relevance check: Did the response answer the user's inquiry?
        String lowerOut = agentOutput.toLowerCase();
        String lowerIn = userInput.toLowerCase();

        if (lowerIn.contains("order") && !lowerOut.contains("order")) {
            relevance -= 25.0;
            reasoning.append("Output omitted order reference. ");
        }
        if ((lowerIn.contains("refund") || lowerIn.contains("damaged")) && !lowerOut.contains("refund")) {
            relevance -= 30.0;
            reasoning.append("Failed to address requested refund resolution. ");
        }

        // 2. Faithfulness check: Are the facts grounded in tool executions?
        if (toolsInvoked.isEmpty()) {
            faithfulness -= 50.0;
            reasoning.append("Agent produced conclusions without executing required tools. ");
        }

        // Check required keywords presence
        if (requiredKeywords != null) {
            for (String kw : requiredKeywords) {
                if (!lowerOut.contains(kw.toLowerCase())) {
                    faithfulness -= (20.0 / Math.max(1, requiredKeywords.size()));
                    reasoning.append("Expected verified evidence '").append(kw).append("' missing in response. ");
                }
            }
        }

        relevance = Math.max(0.0, Math.min(100.0, relevance));
        faithfulness = Math.max(0.0, Math.min(100.0, faithfulness));

        if (reasoning.isEmpty()) {
            reasoning.append("Response is strictly grounded in tool observations and satisfies customer requirements.");
        }

        return new Judgment(faithfulness, relevance, reasoning.toString());
    }
}
